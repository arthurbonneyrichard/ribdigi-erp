"""Gym insights: churn risk, attendance trends, equipment, a plain summary, and draft workout plans.

These are calculated from the gym's own records with fixed rules. They are NOT a language model:
the platform has no LLM client wired for gyms, so nothing here is called AI-generated. Every
response says `method: "rules"` so a screen can say so. A manager can switch insights off.
Nothing is sent to an outside service. Workout drafts are templates for a trainer to review, and
nothing here is medical or nutrition advice.
"""

from __future__ import annotations

from datetime import date, datetime, timedelta

from fastapi import HTTPException
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app import gym as base
from app import models as m
from app.gym import _audit, _member

METHOD = "rules"
NOTE = "Calculated from your own records with fixed rules. Not generated by a language model."


async def is_enabled(db: AsyncSession, tenant_id: str) -> bool:
    row = (await db.execute(select(m.GymSettings).where(m.GymSettings.tenant_id == tenant_id))).scalar_one_or_none()
    return True if row is None else bool(row.insights_enabled)


async def require_enabled(db: AsyncSession, tenant_id: str) -> None:
    if not await is_enabled(db, tenant_id):
        raise HTTPException(status_code=403, detail={"code": "GYM_INSIGHTS_OFF", "message": "A manager has switched gym insights off."})


async def set_enabled(db: AsyncSession, tenant_id: str, enabled: bool, *, user_id) -> dict:
    row = (await db.execute(select(m.GymSettings).where(m.GymSettings.tenant_id == tenant_id).with_for_update())).scalar_one_or_none()
    if row is None:
        row = m.GymSettings(tenant_id=tenant_id, insights_enabled=enabled)
        db.add(row)
    row.insights_enabled, row.updated_at = enabled, datetime.utcnow()
    await db.flush()
    await _audit(db, tenant_id, user_id, "gym_insights_on" if enabled else "gym_insights_off", "gym_settings", row.id, {})
    return {"insights_enabled": enabled}


def _wrap(data: dict) -> dict:
    return {"method": METHOD, "note": NOTE, **data}


async def churn_risk(db: AsyncSession, tenant_id: str, *, limit: int = 50) -> dict:
    """Active members ranked by how likely they are to leave, each with the reasons behind the score."""
    today = date.today()
    d30 = datetime.combine(today - timedelta(days=30), datetime.min.time())
    d60 = datetime.combine(today - timedelta(days=60), datetime.min.time())
    members = (await db.execute(select(m.GymMember).where(m.GymMember.tenant_id == tenant_id))).scalars().all()
    visits = (
        await db.execute(
            select(m.GymCheckIn.member_id, m.GymCheckIn.checked_in_at).where(
                m.GymCheckIn.tenant_id == tenant_id, m.GymCheckIn.allowed.is_(True), m.GymCheckIn.checked_in_at >= d60
            )
        )
    ).all()
    by_member: dict[str, list[datetime]] = {}
    for mid, at in visits:
        by_member.setdefault(mid, []).append(at)
    out = []
    for mem in members:
        current = await base._latest(db, tenant_id, mem.id)
        if base._state(current, today) != "active":
            continue
        times = by_member.get(mem.id, [])
        recent = [t for t in times if t >= d30]
        prior = [t for t in times if t < d30]
        last = max(times) if times else None
        score, why = 0, []
        days_since = (today - last.date()).days if last else None
        joined_days = (today - mem.joined_on).days if mem.joined_on else 999
        if last is None and joined_days >= 14:
            score += 40
            why.append("No visits in the last 60 days")
        elif days_since is not None and days_since >= 14:
            score += 35
            why.append(f"Last visit {days_since} days ago")
        elif days_since is not None and days_since >= 7:
            score += 15
            why.append(f"Last visit {days_since} days ago")
        if prior and len(recent) <= len(prior) / 2:
            score += 20
            why.append(f"Visits fell from {len(prior)} to {len(recent)} compared with the month before")
        left = (current.ends_on - today).days
        if left <= 7:
            score += 25
            why.append(f"Plan ends in {left} day{'s' if left != 1 else ''}")
        elif left <= 14:
            score += 10
            why.append(f"Plan ends in {left} days")
        if score == 0:
            continue
        action = (
            "Call or message this week and offer help with a programme" if (days_since or 0) >= 14 or last is None
            else "Remind them their plan is ending and offer to renew" if left <= 14
            else "Check in at their next visit"
        )
        out.append({"member_id": mem.id, "member_name": mem.full_name, "score": min(score, 100), "level": "high" if score >= 60 else "medium" if score >= 30 else "low", "reasons": why, "suggested_action": action})
    out.sort(key=lambda r: -r["score"])
    return _wrap({"as_of": today.isoformat(), "items": out[:limit], "total_at_risk": len(out)})


async def attendance_trends(db: AsyncSession, tenant_id: str, *, weeks: int = 8) -> dict:
    today = date.today()
    start = datetime.combine(today - timedelta(weeks=weeks), datetime.min.time())
    rows = (
        await db.execute(select(m.GymCheckIn.checked_in_at).where(m.GymCheckIn.tenant_id == tenant_id, m.GymCheckIn.allowed.is_(True), m.GymCheckIn.checked_in_at >= start))
    ).scalars().all()
    names = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    by_day, by_hour = [0] * 7, [0] * 24
    for t in rows:
        by_day[t.weekday()] += 1
        by_hour[t.hour] += 1
    half = datetime.combine(today - timedelta(weeks=weeks // 2), datetime.min.time())
    recent, prior = sum(1 for t in rows if t >= half), sum(1 for t in rows if t < half)
    change = round((recent - prior) / prior * 100, 1) if prior else None
    busiest = max(range(7), key=lambda i: by_day[i]) if rows else None
    peak = max(range(24), key=lambda i: by_hour[i]) if rows else None
    notes = []
    if rows:
        notes.append(f"Busiest day is {names[busiest]}, busiest hour is {peak:02d}:00 (times are recorded in UTC).")
    if change is not None:
        notes.append(f"Visits are {'up' if change >= 0 else 'down'} {abs(change)}% on the earlier half of this period.")
    return _wrap(
        {"weeks": weeks, "visits": len(rows), "by_weekday": dict(zip(names, by_day)), "by_hour": {f"{h:02d}": n for h, n in enumerate(by_hour) if n},
         "recent_half": recent, "earlier_half": prior, "change_pct": change, "notes": notes}
    )


async def equipment_insights(db: AsyncSession, tenant_id: str) -> dict:
    now = datetime.utcnow()
    since = now - timedelta(days=90)
    rows = (await db.execute(select(m.GymMaintenance, m.GymEquipment.name).join(m.GymEquipment, m.GymEquipment.id == m.GymMaintenance.equipment_id).where(m.GymMaintenance.tenant_id == tenant_id, m.GymMaintenance.opened_at >= since))).all()
    per: dict[str, dict] = {}
    for fault, name in rows:
        e = per.setdefault(fault.equipment_id, {"equipment_id": fault.equipment_id, "name": name, "faults_90d": 0, "open": 0, "oldest_open_days": 0})
        e["faults_90d"] += 1
        if fault.status == "open":
            e["open"] += 1
            e["oldest_open_days"] = max(e["oldest_open_days"], (now - fault.opened_at).days)
    items = []
    for e in per.values():
        flags = []
        if e["faults_90d"] >= 3:
            flags.append("Three or more faults in 90 days: consider a service or replacement")
        elif e["faults_90d"] == 2:
            flags.append("Second fault in 90 days: worth a check")
        if e["oldest_open_days"] >= 7:
            flags.append(f"A fault has been open for {e['oldest_open_days']} days")
        if flags:
            items.append({**e, "flags": flags})
    items.sort(key=lambda r: (-r["faults_90d"], -r["oldest_open_days"]))
    return _wrap({"items": items})


async def summary(db: AsyncSession, tenant_id: str) -> dict:
    today = date.today()
    this = await base.period_numbers(db, tenant_id, start=today - timedelta(days=29), end=today)
    prev = await base.period_numbers(db, tenant_id, start=today - timedelta(days=59), end=today - timedelta(days=30))
    risk = await churn_risk(db, tenant_id, limit=5)
    bullets = []

    def move(label, a, b):
        if b:
            pct = round((a - b) / b * 100, 1)
            bullets.append(f"{label}: {a:g} against {b:g} the 30 days before ({'+' if pct >= 0 else ''}{pct}%).")
        else:
            bullets.append(f"{label}: {a:g} (nothing in the 30 days before to compare).")

    move("Takings", this["takings"], prev["takings"])
    move("Visits", this["visits"], prev["visits"])
    move("New members", this["new_members"], prev["new_members"])
    move("Renewals", this["renewals"], prev["renewals"])
    high = [r for r in risk["items"] if r["level"] == "high"]
    bullets.append(f"{risk['total_at_risk']} active members show signs of leaving, {len(high)} of them high risk." if risk["total_at_risk"] else "No active member shows signs of leaving.")
    return _wrap({"period_days": 30, "bullets": bullets, "this_period": {k: this[k] for k in ("takings", "visits", "new_members", "renewals", "sold")}, "previous_period": {k: prev[k] for k in ("takings", "visits", "new_members", "renewals", "sold")}})


# --- Draft workout plans (templates for a trainer to review) -------------------------------

_SPLITS = {
    1: [["legs", "chest", "back", "shoulders", "core"]],
    2: [["legs", "glutes", "core"], ["chest", "back", "shoulders", "arms"]],
    3: [["legs", "glutes"], ["chest", "shoulders", "arms"], ["back", "core"]],
    4: [["legs"], ["chest", "arms"], ["back", "core"], ["shoulders", "glutes"]],
    5: [["legs"], ["chest"], ["back"], ["shoulders", "arms"], ["core", "glutes"]],
}
_GOALS = {  # (sets, reps, rest seconds)
    "strength": (4, 5, 120), "muscle": (3, 10, 75), "weight_loss": (3, 15, 45), "endurance": (2, 20, 30),
}
_LEVEL_SETS = {"beginner": -1, "intermediate": 0, "advanced": 1}


async def draft_workout(db: AsyncSession, tenant_id: str, payload) -> dict:
    """Pick exercises from the gym's own library by muscle group. Not saved: the trainer reviews and saves it."""
    await _member(db, tenant_id, payload.member_id)
    lib = (await db.execute(select(m.GymExercise).where(m.GymExercise.tenant_id == tenant_id, m.GymExercise.is_active.is_(True)).order_by(m.GymExercise.name))).scalars().all()
    if not lib:
        raise HTTPException(status_code=409, detail="Add exercises to the library first. The draft is built from them.")
    by_group: dict[str, list] = {}
    for e in lib:
        by_group.setdefault((e.muscle_group or "other").strip().lower(), []).append(e)
    sets, reps, rest = _GOALS[payload.goal]
    sets = max(2, sets + _LEVEL_SETS[payload.level])
    days = _SPLITS[payload.days_per_week]
    lines, missing = [], set()
    for i, groups in enumerate(days):
        for g in groups:
            pool = by_group.get(g)
            if not pool:
                missing.add(g)
                continue
            ex = pool[i % len(pool)]
            lines.append({"exercise_id": ex.id, "exercise": ex.name, "day_of_week": i + 1, "sets": sets, "reps": reps, "rest_seconds": rest})
    if not lines:
        raise HTTPException(status_code=409, detail="None of your exercises are tagged with a muscle group this plan needs (legs, chest, back, shoulders, arms, core, glutes).")
    return _wrap(
        {
            "draft": True, "review_required": True,
            "disclaimer": "A starting template for a trainer to review and adjust. Not medical advice.",
            "name": f"{payload.goal.replace('_', ' ').title()} · {payload.level} · {payload.days_per_week} days",
            "goal": payload.goal.replace("_", " "), "lines": lines, "muscle_groups_missing_from_library": sorted(missing),
        }
    )
